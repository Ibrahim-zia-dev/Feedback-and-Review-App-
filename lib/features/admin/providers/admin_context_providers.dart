// Get all contexts for organization
final organizationContextsProvider =
    FutureProvider.family<List<Context>, String>((ref, organizationId) async {
      final repository = ref.watch(contextRepositoryProvider);
      return repository.getOrganizationContexts(organizationId);
    });

// Get contexts by status
final contextsByStatusProvider =
    FutureProvider.family<
      List<Context>,
      ({String organizationId, ContextStatus status})
    >((ref, params) async {
      final repository = ref.watch(contextRepositoryProvider);
      final contexts = await repository.getOrganizationContexts(
        params.organizationId,
      );
      return contexts.where((c) => c.status == params.status).toList();
    });

